import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';
const mobile = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(mobile, '..');
const compile = async entry => (await build({
  entryPoints: [entry], bundle: true, write: false, format: 'iife', target: ['safari16'], minify: true,
  plugins: [{ name: 'calculator-engine', setup(b) { b.onResolve({ filter: /^\/dist\/index\.js$/ }, () => ({ path: resolve(root, 'src/index.ts') })); } }],
})).outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
let html = await readFile(resolve(root, 'web/index.html'), 'utf8');
const styles = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)">/g)];
for (const [tag, path] of styles) {
  const css = await readFile(resolve(root, path.slice(1)), 'utf8');
  html = html.replace(tag, () => `<style>${css}</style>`);
}
html = html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '');
const nativeCss = await readFile(resolve(mobile, 'bridge/native.css'), 'utf8');
const bootstrap = await compile(resolve(mobile, 'bridge/bootstrap.js'));
const phoneShell = await readFile(resolve(root, 'web/phone-shell.js'), 'utf8');
// Replacement callbacks keep literal $&, $` and $' inside minified JavaScript
// from being interpreted as String.replace substitution patterns.
html = html.replace('</head>', () => `<style>${nativeCss}</style>
<script>/*NATIVE_BOOTSTRAP*/</script>
<script>${bootstrap}</script>
<script>${phoneShell}</script></head>`);
const app = await compile(resolve(root, 'web/app.js'));
html = html.replace('</body>', () => `<script>${app}</script></body>`);
// Validate the delivered scripts, not just the pre-insertion esbuild output.
const embeddedScripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)];
if (embeddedScripts.length !== 4) throw new Error('Offline HTML has an unexpected script boundary.');
if (embeddedScripts[1][1] !== bootstrap || embeddedScripts[3][1] !== app) throw new Error('Offline script contents changed during HTML insertion.');
for (const [index, match] of embeddedScripts.entries()) new Script(match[1], { filename: `offline-script-${index}.js` });
await mkdir(resolve(mobile, 'generated'), { recursive: true });
await writeFile(resolve(mobile, 'generated/calculator.ts'), `// Generated by npm run bundle; edit ../web or ../src instead.\nexport const calculatorHtml = ${JSON.stringify(html)};\n`);
console.log(`Bundled offline calculator: ${Math.round(Buffer.byteLength(html) / 1024)} KB. No localhost or remote assets required.`);
